def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--clean", action="store_true", help="기존 환자 모두 삭제 후 시드")
    args = parser.parse_args()

    db.init_db()

    if args.clean:
        existing = db.list_patients()
        print(f"기존 환자 {len(existing)}명 삭제 중...")
        for p in existing:
            db.delete_patient(p["id"])

    # 환자 시드
    alias_to_id = {}
    for s in STUDENTS:
        # 같은 alias 있으면 skip
        existing_alias = [p["alias"] for p in db.list_patients()]
        if s["alias"] in existing_alias:
            for p in db.list_patients():
                if p["alias"] == s["alias"]:
                    alias_to_id[s["alias"]] = p["id"]
                    break
            print(f"  skip {s['alias']} — 이미 존재")
            continue
        p = db.add_patient(s["alias"], s["gender"], s["age"], s["region"], s["note"])
        alias_to_id[s["alias"]] = p["id"]
        print(f"  + {s['alias']} ({p['id']})")

    # 회기 시드
    print(f"\n회기 {len(SESSIONS)}건 시드 중...")
    n_added = 0
    for sess in SESSIONS:
        alias = sess["alias"]
        if alias not in alias_to_id:
            print(f"  skip — 환자 alias={alias} 없음")
            continue

        # 같은 환자의 같은 session_no면 skip
        existing_sessions = db.list_sessions(alias_to_id[alias])
        if any(s.get("session_no") == sess["session_no"] for s in existing_sessions):
            continue

        s = db.add_session(
            alias_to_id[alias],
            sess["session_date"],
            sess["transcript"],
            session_no=sess["session_no"],
            scope=sess["scope"],
            topic=sess["topic"],
        )
        n_added += 1
        print(f"  + {alias} {sess['session_no']} ({s['id']}) — {sess['topic'][:30]}")

    print(f"\n완료 — 환자 {len(db.list_patients())}명, 회기 신규 {n_added}건.")
    print("팁: 각 회기는 transcript만 들어있고 분석 결과(F1/F2/F3)는 미생성 상태.")
    print("    UI에서 '상담내역 기록·추가' → '회기 선택' → 분석 실행하면 자동 생성됩니다.")


if __name__ == "__main__":
    main()
